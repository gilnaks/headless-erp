#!/usr/bin/env node
// Generates supabase/migrations/0009_framework_reference_data.sql from the vendored sources in supabase/seed/reference/.
// Usage: node scripts/gen-reference-data.mjs
// Port of frappe/geo/country_info.py (import_country_and_currency, add_country_and_currency) and the UOM part of
// erpnext/setup/setup_wizard/operations/install_fixtures.py (add_uom_data), loaded into global tables once.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = (f) => JSON.parse(readFileSync(join(root, "supabase/seed/reference", f), "utf8"));
const SOURCES = JSON.parse(readFileSync(join(root, "supabase/seed/reference/SOURCES.json"), "utf8"));

const countryInfo = src("country_info.json");
const uomData = src("uom_data.json");
const uomConversions = src("uom_conversion_data.json");

const lit = (v) => {
    if (v === null || v === undefined || v === "") return "null";
    if (typeof v === "number") return String(v);
    if (typeof v === "boolean") return v ? "true" : "false";
    if (typeof v === "object" && "sql" in v) return v.sql;
    if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
    return `'${String(v).replaceAll("'", "''")}'`;
};
const values = (rows) => rows.map((r) => `  (${r.map(lit).join(", ")})`).join(",\n");

// Country: Frappe defaults date_format to dd-mm-yyyy and time_format to HH:mm:ss.
const countries = Object.entries(countryInfo).map(([name, c]) => [
    name,
    c.code ?? null,
    c.date_format || "dd-mm-yyyy",
    c.time_format || "HH:mm:ss",
    [...new Set(c.timezones ?? [])],
]);

// Currency: first country (file order) carrying the code wins, as Frappe skips existing currencies. Frappe stores no
// human name (currency_name = code); we store the ICU English name (JSON names are in mixed languages, e.g. USD is
// "Dolar estadounidense"), falling back to the first JSON name, for search.
const intlName = new Intl.DisplayNames(["en"], { type: "currency" });
const currencies = new Map();
for (const c of Object.values(countryInfo)) {
    if (!c.currency) continue;
    const existing = currencies.get(c.currency);
    if (existing) {
        if (!existing.name && c.currency_name) existing.name = c.currency_name;
        continue;
    }
    currencies.set(c.currency, {
        name: c.currency_name || null,
        fraction: c.currency_fraction ?? null,
        units: c.currency_fraction_units ?? null,
        smallest: c.smallest_currency_fraction_value ?? null,
        symbol: c.currency_symbol ?? null,
        format: c.number_format ?? null,
    });
}
const currencyRows = [...currencies.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([code, c]) => {
        const icu = intlName.of(code);
        const name = icu && icu !== code ? icu : c.name || code;
        return [code, name, c.fraction, c.units, c.smallest, c.symbol, false, c.format];
    });

const uomNames = new Set(uomData.map((u) => u.uom_name));
if (uomNames.size !== uomData.length) throw new Error("duplicate uom_name in uom_data.json");
const uomRows = uomData.map((u) => [u.uom_name, u.category, Boolean(u.must_be_whole_number)]);

// ERPNext db_inserts conversions without link validation; a few reference UOMs missing from uom_data.json.
const danglingUoms = [...new Set(uomConversions.flatMap((c) => [c.from_uom, c.to_uom]).filter((u) => !uomNames.has(u)))].sort();
const seen = new Set();
const conversionRows = [];
const repaired = [];
for (const c of uomConversions) {
    const key = `${c.from_uom}\u0000${c.to_uom}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const raw = String(c.value).trim();
    const numeric = /^-?\d+(\.\d+)?/.exec(raw)?.[0];
    if (!numeric) throw new Error(`bad conversion value ${c.from_uom} -> ${c.to_uom}: ${c.value}`);
    if (numeric !== raw) repaired.push(`${c.from_uom} -> ${c.to_uom} "${c.value}"`);
    conversionRows.push([c.category, c.from_uom, c.to_uom, { sql: numeric }]);
}

const sql = `-- 0009 framework: global reference data (Country, Currency, UOM templates) + per-org enabled currencies.
-- GENERATED by scripts/gen-reference-data.mjs from supabase/seed/reference/ — do not edit by hand; edit the generator
-- or the vendored sources and regenerate.
-- Sources: frappe/geo/country_info.json @ frappe/frappe ${SOURCES.frappe}
--          erpnext/setup/setup_wizard/data/uom_data.json, uom_conversion_data.json @ frappe/erpnext ${SOURCES.erpnext}
-- Ports frappe/geo/country_info.py (import_country_and_currency): Country rows default date_format dd-mm-yyyy and
-- time_format HH:mm:ss; a currency is created by the first country (file order) that carries it.
-- Deviations: currency.currency_name holds the human name (Frappe stores the code there) so pickers can search by name;
-- Frappe's global Currency.enabled flag becomes per-org org_currency (multi-tenancy). Company links live in 0101.
-- Conversion values with stray characters are read as their numeric prefix (Frappe's flt() would store 0): ${repaired.join("; ") || "none"}.
-- Counts: ${countries.length} countries, ${currencyRows.length} currencies, ${uomRows.length} UOMs, ${conversionRows.length} conversions.

create table if not exists public.country (
  country_name text primary key,
  code         text,
  date_format  text not null default 'dd-mm-yyyy',
  time_format  text not null default 'HH:mm:ss',
  time_zones   text[] not null default '{}'
);

create table if not exists public.currency (
  code                             text primary key,
  currency_name                    text not null,
  fraction                         text,
  fraction_units                   integer,
  smallest_currency_fraction_value numeric(21,9),
  symbol                           text,
  symbol_on_right                  boolean not null default false,
  number_format                    text
);

create table if not exists public.uom_template (
  uom_name             text primary key,
  category             text,
  must_be_whole_number boolean not null default false
);

-- value mirrors ERPNext's Float column (decimal(21,9)). No FK to uom_template: ERPNext inserts these rows without link
-- validation and ${danglingUoms.length} of them name UOMs absent from uom_data.json (${danglingUoms.join(", ")}).
create table if not exists public.uom_conversion_template (
  category text not null,
  from_uom text not null,
  to_uom   text not null,
  value    numeric(21,9) not null,
  primary key (from_uom, to_uom)
);

-- Read-only for signed-in users; rows change only through migrations.
do $$
declare t text;
begin
  foreach t in array array['country', 'currency', 'uom_template', 'uom_conversion_template'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('alter table public.%I force row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('create policy %I on public.%I for select to authenticated using (true)', t || '_select', t);
    execute format('revoke insert, update, delete, truncate on public.%I from anon, authenticated', t);
  end loop;
end;
$$;

insert into public.country (country_name, code, date_format, time_format, time_zones) values
${values(countries)}
on conflict (country_name) do update set
  code = excluded.code, date_format = excluded.date_format, time_format = excluded.time_format,
  time_zones = excluded.time_zones;

insert into public.currency (code, currency_name, fraction, fraction_units, smallest_currency_fraction_value, symbol,
  symbol_on_right, number_format) values
${values(currencyRows)}
on conflict (code) do update set
  currency_name = excluded.currency_name, fraction = excluded.fraction, fraction_units = excluded.fraction_units,
  smallest_currency_fraction_value = excluded.smallest_currency_fraction_value, symbol = excluded.symbol,
  symbol_on_right = excluded.symbol_on_right, number_format = excluded.number_format;

insert into public.uom_template (uom_name, category, must_be_whole_number) values
${values(uomRows)}
on conflict (uom_name) do update set
  category = excluded.category, must_be_whole_number = excluded.must_be_whole_number;

insert into public.uom_conversion_template (category, from_uom, to_uom, value) values
${values(conversionRows)}
on conflict (from_uom, to_uom) do update set category = excluded.category, value = excluded.value;

------------------------------------------------------------------------------------------------------------------------
-- Per-org enabled currencies (Frappe Currency.enabled; ERPNext enables the company/default currency on save)
------------------------------------------------------------------------------------------------------------------------

create table if not exists public.org_currency (
  org_id     uuid not null references public.organizations (id) on delete cascade,
  code       text not null references public.currency (code) on update cascade,
  enabled    boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid,
  primary key (org_id, code)
);

drop trigger if exists touch_updated on public.org_currency;
create trigger touch_updated before update on public.org_currency
  for each row execute function app.touch_updated();

alter table public.org_currency enable row level security;
alter table public.org_currency force row level security;

drop policy if exists org_currency_select on public.org_currency;
create policy org_currency_select on public.org_currency for select to authenticated
  using (org_id = any ((select app.user_org_ids())::uuid[]));
drop policy if exists org_currency_update on public.org_currency;
create policy org_currency_update on public.org_currency for update to authenticated
  using (org_id = any ((select app.orgs_with_role('System Manager'))::uuid[]))
  with check (org_id = any ((select app.orgs_with_role('System Manager'))::uuid[]));

create or replace function app.enable_org_currency(p_org uuid, p_code text)
returns void
language sql
security definer
set search_path = ''
as $fn$
  insert into public.org_currency (org_id, code, enabled) values (p_org, p_code, true)
  on conflict (org_id, code) do update set enabled = true where not public.org_currency.enabled;
$fn$;

revoke execute on function app.enable_org_currency(uuid, text) from public, anon, authenticated;

------------------------------------------------------------------------------------------------------------------------
-- Link validation (Frappe LinkValidationError "Could not find {doctype}: {value}")
------------------------------------------------------------------------------------------------------------------------

create or replace function app.validate_country_currency(p_country text, p_currency text)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $fn$
begin
  if p_country is not null and not exists (select 1 from public.country where country_name = p_country) then
    raise exception using errcode = 'P0001', message = format('country_unknown: Could not find Country: %s', p_country);
  end if;
  if p_currency is not null and not exists (select 1 from public.currency where code = p_currency) then
    raise exception using errcode = 'P0001', message = format('currency_unknown: Could not find Currency: %s', p_currency);
  end if;
end;
$fn$;

-- Trigger functions are security definer because the helpers they call are not executable by API roles.
create or replace function app.organizations_validate_links()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  perform app.validate_country_currency(new.country, new.default_currency);
  return new;
end;
$fn$;

create or replace function app.organizations_enable_currency()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if new.default_currency is not null then
    perform app.enable_org_currency(new.id, new.default_currency);
  end if;
  return null;
end;
$fn$;

revoke execute on function
  app.validate_country_currency(text, text), app.organizations_validate_links(), app.organizations_enable_currency()
from public, anon, authenticated;

drop trigger if exists organizations_validate_links on public.organizations;
create trigger organizations_validate_links
  before insert or update of country, default_currency on public.organizations
  for each row execute function app.organizations_validate_links();

drop trigger if exists organizations_enable_currency on public.organizations;
create trigger organizations_enable_currency
  after insert or update of default_currency on public.organizations
  for each row execute function app.organizations_enable_currency();

alter table public.organizations drop constraint if exists organizations_country_fkey;
alter table public.organizations add constraint organizations_country_fkey
  foreign key (country) references public.country (country_name) on update cascade;
alter table public.organizations drop constraint if exists organizations_default_currency_fkey;
alter table public.organizations add constraint organizations_default_currency_fkey
  foreign key (default_currency) references public.currency (code) on update cascade;

-- Existing organizations get their currency enabled.
insert into public.org_currency (org_id, code)
select id, default_currency from public.organizations where default_currency is not null
on conflict do nothing;

-- UOM is registered by the per-org uom table (P1); the template is not a doctype.
insert into public.doctype_meta (doctype, table_name, module, title_field) values
  ('Country', 'country', 'setup', 'country_name'),
  ('Currency', 'currency', 'setup', 'code')
on conflict (doctype) do update
  set table_name = excluded.table_name, module = excluded.module, title_field = excluded.title_field;
`;

writeFileSync(join(root, "supabase/migrations/0009_framework_reference_data.sql"), sql.replaceAll("\r\n", "\n"));
console.log(`countries=${countries.length} currencies=${currencyRows.length} uoms=${uomRows.length} conversions=${conversionRows.length}`);
