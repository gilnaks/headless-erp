#!/usr/bin/env node
// Generates supabase/migrations/0115_setup_coa_templates.sql from the vendored charts in supabase/seed/coa/.
// Usage: node scripts/gen-coa-templates.mjs
// Port of erpnext/accounts/doctype/account/chart_of_accounts/chart_of_accounts.py (get_chart, get_charts_for_country,
// build_tree_from_json, identify_is_group) over a global coa_template table loaded once.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { minifyJson, pythonChartToJson, treeText } from "./lib/coa.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const coaDir = join(root, "supabase/seed/coa");
const SOURCES = JSON.parse(readFileSync(join(root, "supabase/seed/reference/SOURCES.json"), "utf8"));
const read = (path) => readFileSync(path, "utf8").replace(/^\uFEFF/, "");
const lit = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);

// Standard charts are Python modules in ERPNext (get_chart "Standard" / "Standard with Numbers").
const templates = new Map([
    ["Standard", { tree: pythonChartToJson(read(join(coaDir, "standard_chart_of_accounts.py"))), disabled: false }],
    [
        "Standard with Numbers",
        { tree: pythonChartToJson(read(join(coaDir, "standard_chart_of_accounts_with_account_number.py"))), disabled: false },
    ],
]);
const files = [];
const duplicates = [];

for (const file of readdirSync(join(coaDir, "verified")).filter((f) => f.endsWith(".json")).sort()) {
    const text = minifyJson(read(join(coaDir, "verified", file)));
    const doc = JSON.parse(text);
    const tree = treeText(text);
    const existing = templates.get(doc.name);
    if (existing) {
        // get_chart returns the first file carrying the name; the copies (Syscohada per country, written by
        // syscohada_chart_of_accounts.py with \\u escapes) must hold the same accounts.
        const same = JSON.stringify(JSON.parse(existing.tree)) === JSON.stringify(JSON.parse(tree));
        if (!same) throw new Error(`${file}: chart "${doc.name}" differs from an earlier file`);
        duplicates.push(file);
    } else {
        templates.set(doc.name, { tree, disabled: doc.disabled === "Yes" });
    }
    files.push([file, doc.name]);
}

const templateRows = [...templates].map(([name, t]) => `  (${lit(name)}, ${t.disabled}, ${lit(t.tree)}::json)`).join(",\n");
const fileRows = files.map(([file, name]) => `  (${lit(file)}, ${lit(name)})`).join(",\n");

const sql = `-- 0115 setup: chart of accounts templates (docs/modules/00-setup.md §3.2). GENERATED by scripts/gen-coa-templates.mjs; do
-- not edit by hand. Sources: erpnext/accounts/doctype/account/chart_of_accounts/verified/*.json and
-- standard_chart_of_accounts{,_with_account_number}.py @ frappe/erpnext ${SOURCES.erpnext}.
-- Ports chart_of_accounts.py: get_chart (by template name), get_charts_for_country (file name starts with the country
-- code or name; disabled charts skipped), build_tree_from_json + identify_is_group (preview). Trees are stored as json,
-- not jsonb, to keep ERPNext's account order. Accounts are created from these templates when the account table lands.
-- Counts: ${templates.size} templates, ${files.length} files (${duplicates.length} copies of an earlier chart).

create table if not exists public.coa_template (
  name     text primary key,
  disabled boolean not null default false,
  tree     json not null
);

-- One row per vendored file: get_charts_for_country matches file names, several files may carry one chart.
create table if not exists public.coa_template_file (
  file_name text primary key,
  template  text not null references public.coa_template (name) on update cascade on delete cascade
);

do $$
declare t text;
begin
  foreach t in array array['coa_template', 'coa_template_file'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('alter table public.%I force row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('create policy %I on public.%I for select to authenticated using (true)', t || '_select', t);
    execute format('revoke insert, update, delete, truncate on public.%I from anon, authenticated', t);
  end loop;
end;
$$;

insert into public.coa_template (name, disabled, tree) values
${templateRows}
on conflict (name) do update set disabled = excluded.disabled, tree = excluded.tree;

insert into public.coa_template_file (file_name, template) values
${fileRows}
on conflict (file_name) do update set template = excluded.template;

-- get_charts_for_country: a file belongs to a country when its name starts with the country code or the country name
-- (case-sensitive, as os.listdir + startswith).
create or replace view public.coa_template_country with (security_invoker = true) as
select distinct c.country_name, f.template
  from public.coa_template_file f
  join public.coa_template t on t.name = f.template and not t.disabled
  join public.country c on (c.code is not null and starts_with(f.file_name, c.code)) or starts_with(f.file_name, c.country_name);

-- Templates offered for a country: its charts, then Standard and Standard with Numbers (get_charts_for_country with
-- with_standard, as the company form and setup wizard ask). is_default marks the single country chart, else Standard.
create or replace function app.coa_templates_for_country(p_country text)
returns table (name text, is_default boolean)
language sql
stable
set search_path = ''
as $fn$
  with matched as (
    select v.template from public.coa_template_country v where v.country_name = p_country
  ), n as (select count(*) as c from matched)
  select x.name, x.is_default from (
    select m.template as name, (select c from n) = 1 as is_default, 0 as ord from matched m
    union all
    select s.name, (select c from n) <> 1 and s.name = 'Standard', s.ord
      from (values (1, 'Standard'), (2, 'Standard with Numbers')) s(ord, name)
  ) x
  order by x.ord, x.name;
$fn$;

-- build_tree_from_json: one row per account in chart order; value = "<number> - <name>" when numbered, groups by
-- identify_is_group (explicit is_group, else any non-metadata key). root_type comes from the root account.
create or replace function app.coa_template_preview(p_template text)
returns table (idx int, account text, parent_account text, is_group boolean, root_type text, account_type text,
               account_number text, depth int)
language sql
stable
set search_path = ''
as $fn$
  with recursive nodes as (
    select e.key as name, e.value as node, null::text as parent_account, e.value ->> 'root_type' as root_type, 0 as depth,
           array[e.ord] as path
      from public.coa_template t, json_each(t.tree) with ordinality e(key, value, ord)
     where t.name = p_template and json_typeof(e.value) = 'object'
       and e.key <> all (array['account_name', 'account_number', 'account_type', 'account_category', 'root_type',
                               'is_group', 'tax_rate', 'account_currency'])
    union all
    select c.key, c.value,
           case when nullif(trim(n.node ->> 'account_number'), '') is not null
                then trim(n.node ->> 'account_number') || ' - ' || n.name else n.name end,
           n.root_type, n.depth + 1, n.path || c.ord
      from nodes n, json_each(n.node) with ordinality c(key, value, ord)
     where json_typeof(c.value) = 'object'
       and c.key <> all (array['account_name', 'account_number', 'account_type', 'account_category', 'root_type',
                               'is_group', 'tax_rate', 'account_currency'])
  )
  select row_number() over (order by path)::int,
         case when nullif(trim(node ->> 'account_number'), '') is not null
              then trim(node ->> 'account_number') || ' - ' || name else name end,
         parent_account,
         coalesce(nullif(node ->> 'is_group', '') not in ('0', 'false'), false)
           or exists (select 1 from json_object_keys(node) k
                       where k <> all (array['account_name', 'account_number', 'account_type', 'account_category',
                                             'root_type', 'is_group', 'tax_rate', 'account_currency'])),
         root_type,
         nullif(node ->> 'account_type', ''),
         nullif(trim(node ->> 'account_number'), ''),
         depth
    from nodes
   order by path;
$fn$;

revoke execute on function app.coa_templates_for_country(text), app.coa_template_preview(text) from public, anon, authenticated;
grant execute on function app.coa_templates_for_country(text), app.coa_template_preview(text) to authenticated;

create or replace function public.coa_templates_for_country(p_country text)
returns table (name text, is_default boolean)
language sql
stable
security invoker
set search_path = ''
as $fn$
  select * from app.coa_templates_for_country(p_country);
$fn$;

create or replace function public.coa_template_preview(p_template text)
returns table (idx int, account text, parent_account text, is_group boolean, root_type text, account_type text,
               account_number text, depth int)
language sql
stable
security invoker
set search_path = ''
as $fn$
  select * from app.coa_template_preview(p_template);
$fn$;

revoke execute on function public.coa_templates_for_country(text), public.coa_template_preview(text) from public, anon;
grant execute on function public.coa_templates_for_country(text), public.coa_template_preview(text) to authenticated;

------------------------------------------------------------------------------------------------------------------------
-- Company: chart_of_accounts must name a template (Frappe LinkValidationError wording, mapped onto the field)
------------------------------------------------------------------------------------------------------------------------

create or replace function app.companies_validate_links()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  perform app.validate_country_currency(new.country, new.default_currency);
  if new.chart_of_accounts is not null
     and (tg_op = 'INSERT' or new.chart_of_accounts is distinct from old.chart_of_accounts)
     and not exists (select 1 from public.coa_template t where t.name = new.chart_of_accounts and not t.disabled) then
    raise exception using errcode = 'P0001',
      message = format('coa_unknown: Could not find Chart Of Accounts Template: %s', new.chart_of_accounts);
  end if;
  return new;
end;
$fn$;

alter table public.companies drop constraint if exists companies_chart_of_accounts_fkey;
alter table public.companies add constraint companies_chart_of_accounts_fkey
  foreign key (chart_of_accounts) references public.coa_template (name) on update cascade;
`;

writeFileSync(join(root, "supabase/migrations/0115_setup_coa_templates.sql"), sql.replaceAll("\r\n", "\n"));
console.log(`templates=${templates.size} files=${files.length} copies=${duplicates.length}`);
